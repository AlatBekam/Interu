// Regenerate the bundled CISA KEV snapshot as a framework-free .ts module.
// Usage:  node scripts/update-kev.mjs
// Fetches the public CISA Known Exploited Vulnerabilities feed and writes a
// trimmed, cveID-keyed index to src/shared/kev-index.ts (committed to the repo),
// so the app needs no network at runtime. Re-run to refresh.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const FEED = 'https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json'
const OUT = fileURLToPath(new URL('../src/shared/kev-index.ts', import.meta.url))

const res = await fetch(FEED)
if (!res.ok) { console.error(`fetch failed: HTTP ${res.status}`); process.exit(1) }
const data = await res.json()
const vulns = Array.isArray(data.vulnerabilities) ? data.vulnerabilities : []
if (vulns.length === 0) { console.error('no vulnerabilities in feed'); process.exit(1) }

// Trim to only what the UI/enrichment needs, keyed by CVE id.
const index = {}
for (const v of vulns) {
  if (!v.cveID) continue
  const e = { name: v.vulnerabilityName || v.cveID, vendor: v.vendorProject || '', product: v.product || '', dateAdded: v.dateAdded || '' }
  if (v.dueDate) e.dueDate = v.dueDate
  if (v.knownRansomwareCampaignUse === 'Known') e.ransomware = true
  index[v.cveID] = e
}

const header = `// AUTO-GENERATED by scripts/update-kev.mjs — do not edit by hand.
// Source: CISA Known Exploited Vulnerabilities catalog (public feed).
// Trimmed snapshot; re-run the script to refresh.
export interface KevEntry {
  name: string
  vendor: string
  product: string
  dateAdded: string
  dueDate?: string
  ransomware?: boolean
}
export const KEV_CATALOG_VERSION = ${JSON.stringify(data.catalogVersion || data.dateReleased || 'unknown')}
export const KEV_COUNT = ${Object.keys(index).length}
export const KEV: Record<string, KevEntry> = ${JSON.stringify(index, null, 0)}
`
writeFileSync(OUT, header, 'utf8')
console.log(`wrote ${OUT}\n  catalogVersion=${data.catalogVersion || '(none)'} entries=${Object.keys(index).length}`)
